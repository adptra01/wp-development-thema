<h2>Pendahuluan</h2>
<p>Pedoman Media Siber ini adalah pedoman bagi Jambi Press dalam menyelenggarakan jurnalisme di media siber. Pedoman ini disusun berdasarkan Peraturan Dewan Pers Nomor: 1/Peraturan-DP/III/2012 tentang Pedoman Pemberitaan Media Siber dan merupakan bagian dari upaya Jambi Press untuk menghadirkan berita yang akurat, berimbang, dan bertanggung jawab.</p>

<h2>1. Ruang Lingkup</h2>
<p>Media siber adalah segala bentuk media yang menggunakan internet dan teknologi digital sebagai sarana penyampaian informasi. Jambi Press sebagai media siber memiliki tanggung jawab untuk mematuhi Undang-Undang Nomor 40 Tahun 1999 tentang Pers, Kode Etik Jurnalistik, serta Pedoman Media Siber yang ditetapkan oleh Dewan Pers.</p>

<h2>2. Verifikasi dan Keberimbangan Berita</h2>
<p>Setiap berita yang dimuat di Jambi Press harus melalui proses verifikasi yang ketat. Prinsip keberimbangan (cover both sides) wajib diterapkan dalam setiap pemberitaan, khususnya untuk berita-berita yang mengandung kontroversi atau menyangkut kepentingan publik.</p>
<p>Untuk berita yang bersifat cepat (breaking news), Jambi Press wajib menyebutkan sumber informasi dan melakukan verifikasi tambahan sesegera mungkin. Berita yang belum terverifikasi sepenuhnya harus dicantumkan keterangan bahwa berita tersebut masih perlu diverifikasi lebih lanjut.</p>

<h2>3. Isi Buatan Pengguna (User Generated Content)</h2>
<p>Jambi Press membuka ruang partisipasi kepada pengguna melalui fitur komentar, forum, dan kontribusi warga (citizen journalism). Seluruh isi buatan pengguna harus melalui penyuntingan dan verifikasi sebelum dimuat apabila menyangkut fakta dan data.</p>
<p>Jambi Press berhak untuk menghapus atau tidak menayangkan konten pengguna yang:</p>
<ul>
  <li>Mengandung unsur pornografi, SARA, dan ujaran kebencian</li>
  <li>Melanggar hak cipta pihak lain</li>
  <li>Berisi fitnah, hoaks, atau informasi yang menyesatkan</li>
  <li>Melanggar ketentuan hukum yang berlaku di Indonesia</li>
</ul>

<h2>4. Ralat, Koreksi, dan Hak Jawab</h2>
<p>Apabila terdapat kesalahan dalam pemberitaan, Jambi Press wajib melakukan ralat dan koreksi secara transparan. Ralat dimuat di tempat yang mudah diakses dan dengan format yang jelas. Jambi Press juga wajib melayani hak jawab sebagaimana diatur dalam Undang-Undang Pers dan Kode Etik Jurnalistik.</p>
<p>Mekanisme hak jawab:</p>
<ul>
  <li>Pemohon hak jawab mengajukan permohonan secara tertulis kepada redaksi</li>
  <li>Redaksi wajib memproses permohonan dalam waktu paling lambat 7 hari kerja</li>
  <li>Hak jawab dimuat secara proporsional dan menonjol</li>
</ul>

<h2>5. Pencabutan Berita</h2>
<p>Pencabutan berita hanya dapat dilakukan jika:</p>
<ul>
  <li>Berita terbukti palsu atau hoaks berdasarkan putusan pengadilan atau Dewan Pers</li>
  <li>Berita mengandung kesalahan fatal yang tidak dapat diperbaiki melalui ralat</li>
  <li>Pencabutan berita wajib disertai dengan alasan yang jelas dan transparan kepada publik</li>
</ul>

<h2>6. Iklan</h2>
<p>Jambi Press membedakan secara tebas antara konten berita dan iklan. Setiap iklan yang dimuat wajib mencantumkan label "Iklan", "Advertorial", atau "Sponsored" yang jelas sehingga tidak menyesatkan pembaca. Materi iklan tidak boleh bertentangan dengan peraturan perundang-undangan dan nilai-nilai kesusilaan.</p>

<h2>7. Hak Cipta</h2>
<p>Seluruh konten yang diproduksi oleh Jambi Press dilindungi oleh Undang-Undang Hak Cipta. Penggunaan kembali konten Jambi Press oleh pihak lain wajib mencantumkan sumber yang jelas dan mendapatkan izin tertulis apabila digunakan untuk tujuan komersial.</p>

<h2>8. Pencantuman Pedoman</h2>
<p>Pedoman Media Siber ini wajib dicantumkan dan dapat diakses oleh publik melalui situs Jambi Press. Setiap insan Jambi Press wajib memahami dan menjalankan pedoman ini dalam tugas jurnalistik sehari-hari.</p>

<h2>9. Sengketa</h2>
<p>Apabila terjadi sengketa terkait pemberitaan di Jambi Press, penyelesaian dilakukan melalui mekanisme yang diatur dalam Undang-Undang Pers dan Kode Etik Jurnalistik. Para pihak dapat mengajukan pengaduan ke Dewan Pers apabila tidak mencapai kesepakatan melalui mediasi internal.</p>

